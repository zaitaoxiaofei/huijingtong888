export function isTenantPilotRoute(path, method) {
  const verb = String(method || 'GET').toUpperCase();
  return routes.has(`${verb} ${path}`) || recordRoutes.some(([verbs, pattern]) => verbs.split('|').includes(verb) && pattern.test(path));
}

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'pdd-invoice-assistant');
const target = path.join(root, 'ozon-erp-collector-plugin', 'pdd-invoice');
await fs.mkdir(target, { recursive: true });
for (const file of ['core.js', 'content.js', 'dashboard.html', 'dashboard.css', 'dashboard.js']) {
  await fs.copyFile(path.join(source, file), path.join(target, file));
}
await fs.cp(path.join(source, 'icons'), path.join(target, 'icons'), { recursive: true });

let reader = await fs.readFile(path.join(source, 'page-reader.js'), 'utf8');
reader = reader.replaceAll('export function ', 'function ');
let worker = await fs.readFile(path.join(source, 'background.js'), 'utf8');
worker = worker.replace(/^import .*;\n/gm, '');
// Storage access level is extension-wide: the Ozon content scripts keep their
// existing configuration access. Only the PDD state key is owned by this module.
worker = worker.replace('  await chrome.storage.local.setAccessLevel({accessLevel: "TRUSTED_CONTEXTS"});\n', '');
worker = worker.replace('const boot = (async () => {', 'let boot;\nfunction ensureBoot() { return boot ||= (async () => {');
worker = worker.replace('})();', '})(); }');
worker = worker.replaceAll('await boot;', 'await ensureBoot();');
worker = worker.replace('chrome.runtime.getURL("dashboard.html")', 'chrome.runtime.getURL("pdd-invoice/dashboard.html")');
const actionStart = worker.indexOf('chrome.action.onClicked.addListener(');
const actionEnd = worker.indexOf('chrome.alarms.onAlarm.addListener(', actionStart);
if (actionStart < 0 || actionEnd < 0) throw new Error('PDD action adapter anchors missing');
worker = worker.slice(0, actionStart) + worker.slice(actionEnd);
// The shared ERP popup and badge retain ownership of extension-level UI.
worker = worker.replace(/^    await chrome\.action\.setBadge(?:Text|BackgroundColor)\([^\n]+\);\n/gm, '');
await fs.writeFile(path.join(target, 'background.js'), `// Generated by scripts/sync-unified-pdd-invoice.mjs.\n(() => {\n'use strict';\n${reader}\n${worker}\n})();\n`, 'utf8');
let help = await fs.readFile(path.join(source, 'README.md'), 'utf8');
help = help.replace(/^# .*\n/, '# 爆单ERP · 采购开票\n');
help = help.replace(/## 安装[\s\S]*?## 开始处理/, '## 入口\n\n安装或更新爆单ERP统一插件后，点击工具栏插件图标，再点击「拼多多采购开票」。无需另装独立开票插件。保留原来的 ERP 插件安装目录并重新加载，可继续使用既有 ERP 配置。\n\n独立试用版和统一插件属于不同扩展存储空间，独立版记录不会自动转移；迁移前请保留独立版及其导出台账。\n\n## 开始处理');
await fs.writeFile(path.join(target, 'README.md'), help, 'utf8');
console.log('Unified PDD invoice module synchronized.');
